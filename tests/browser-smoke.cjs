// Optional browser verification. Set PLAYWRIGHT_MODULE to an existing Playwright
// installation; this script does not add or install a project dependency.
const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const baseURL = process.env.BASE_URL || 'http://localhost:3000';
const key = 'folio.tasks.v1';

(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const rows = page.locator('.task-row');
  const panel = page.locator('#task-panel');
  const loaded = async count => { await page.waitForFunction(expected => document.querySelectorAll('.task-row').length === expected && document.querySelector('#task-list').getAttribute('aria-busy') === 'false', count); };
  const closePanel = async () => { await page.getByRole('button', { name: 'Close task panel' }).click(); };
  const fillTask = async title => {
    await panel.getByLabel('Task title', { exact: true }).fill(title);
    await panel.getByLabel('Description', { exact: true }).fill('A unique searchneedle for automated checking.');
    await panel.getByLabel('Priority', { exact: true }).selectOption('High');
    await panel.getByLabel('Assignee', { exact: true }).fill('Rui');
    await panel.getByLabel('Due date', { exact: true }).fill('2026-10-12');
  };
  try {
    await page.goto(baseURL); await loaded(6);
    await page.screenshot({ path: path.join(__dirname, '../artifacts/folio-desktop.png'), fullPage: true });
    await page.getByRole('button', { name: 'New task', exact: true }).click();
    await page.getByRole('button', { name: 'Create task', exact: true }).click();
    await page.locator('#error-title').waitFor({ state: 'visible' });
    assert.match(await page.locator('#error-title').innerText(), /between 1 and 160/);
    await fillTask('UI smoke task');
    await page.getByRole('button', { name: 'Create task', exact: true }).click();
    await panel.getByRole('heading', { name: 'UI smoke task', exact: true }).waitFor();
    assert.match(await panel.innerText(), /searchneedle/);
    const initial = await page.evaluate(storageKey => JSON.parse(localStorage.getItem(storageKey)).find(task => task.title === 'UI smoke task'), key);
    await page.getByRole('button', { name: 'Edit task', exact: false }).click();
    await page.getByLabel('Task title', { exact: true }).fill('UI smoke task edited');
    await page.getByLabel('Status', { exact: true }).selectOption('Under Review');
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    await panel.getByRole('heading', { name: 'UI smoke task edited', exact: true }).waitFor();
    await closePanel(); await page.reload(); await loaded(7);
    const persisted = await page.evaluate(storageKey => JSON.parse(localStorage.getItem(storageKey)).find(task => task.title === 'UI smoke task edited'), key);
    assert.equal(persisted.id, initial.id); assert.equal(persisted.createdAt, initial.createdAt);
    await page.getByRole('searchbox').fill('SEARCHNEEDLE'); await loaded(1);
    await page.getByRole('searchbox').fill('no-such-task');
    await page.getByRole('heading', { name: 'No tasks match just yet.' }).waitFor();
    await page.getByRole('button', { name: 'Clear filters', exact: true }).last().click(); await loaded(7);
    await page.getByLabel('Filter by priority').selectOption('High');
    await page.getByLabel('Filter by assignee').selectOption('person:Rui'); await loaded(1);
    await page.getByRole('button', { name: 'Under Review', exact: false }).click(); await loaded(1);
    await page.locator('#clear-filters').click(); await loaded(7);
    await page.getByLabel('Sort tasks').selectOption('title');
    const titles = await page.locator('.task-title-button').allTextContents();
    assert.deepEqual(titles, [...titles].sort((a, b) => a.localeCompare(b)));
    await page.getByRole('button', { name: 'Complete UI smoke task edited', exact: true }).click();
    await page.getByRole('button', { name: 'Reopen UI smoke task edited', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Reopen UI smoke task edited', exact: true }).click();
    await page.getByLabel('Status for UI smoke task edited', { exact: true }).selectOption('In Progress');
    await page.waitForFunction(() => document.querySelector('[aria-label="Status for UI smoke task edited"]').value === 'In Progress');
    await page.getByRole('button', { name: 'UI smoke task edited', exact: true }).click();
    await panel.getByRole('button', { name: 'Delete task', exact: true }).click();
    await page.getByRole('button', { name: 'Keep task', exact: true }).click();
    assert.equal(await rows.count(), 7);
    await panel.getByRole('button', { name: 'Delete task', exact: true }).click();
    await page.locator('#confirm-delete').click(); await loaded(6);
    await page.locator('[data-view=completed]').click(); await loaded(1);
    await page.locator('[data-view=upcoming]').click(); await loaded(4);
    await page.locator('[data-view=all]').click(); await loaded(6);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'mobile page should not scroll horizontally');
    await page.screenshot({ path: path.join(__dirname, '../artifacts/folio-mobile.png'), fullPage: true });
    await page.getByRole('button', { name: 'New task', exact: true }).click();
    assert.equal(await page.evaluate(() => document.activeElement.id), 'field-title');
    await page.keyboard.press('Escape');
    assert.equal(await panel.isVisible(), false);
    // A saved empty array must not seed example tasks again.
    await page.evaluate(storageKey => localStorage.setItem(storageKey, '[]'), key);
    await page.reload(); await page.getByRole('heading', { name: 'A fresh page, just for you.' }).waitFor();
    await page.getByRole('button', { name: 'Add a task', exact: true }).click();
    await fillTask('<img src=x onerror="window.injected=true">');
    await page.getByRole('button', { name: 'Create task', exact: true }).click();
    await panel.getByRole('heading', { name: '<img src=x onerror="window.injected=true">', exact: true }).waitFor();
    assert.equal(await page.evaluate(() => window.injected), undefined, 'task text must not execute HTML');
    await closePanel(); await page.reload(); await loaded(1);
    await page.evaluate(() => {
      const original = Storage.prototype.setItem;
      window.blockWrites = true;
      Storage.prototype.setItem = function (...args) { if (window.blockWrites) throw new Error('Blocked for test'); return original.apply(this, args); };
    });
    await page.getByRole('button', { name: 'New task', exact: true }).click(); await fillTask('Retained draft');
    await page.getByRole('button', { name: 'Create task', exact: true }).click();
    await page.locator('#form-error').waitFor({ state: 'visible' });
    assert.match(await page.locator('#form-error').innerText(), /could not be saved/);
    assert.equal(await page.getByLabel('Task title', { exact: true }).inputValue(), 'Retained draft');
    await page.evaluate(() => { window.blockWrites = false; });
    await page.getByRole('button', { name: 'Create task', exact: true }).click();
    await panel.getByRole('heading', { name: 'Retained draft', exact: true }).waitFor();
    await page.evaluate(() => { window.blockWrites = true; });
    await panel.getByRole('button', { name: 'Delete task', exact: true }).click(); await page.locator('#confirm-delete').click();
    await page.locator('#delete-error').waitFor({ state: 'visible' });
    assert.equal(await rows.count(), 2, 'failed deletion must retain the task');
    await page.getByRole('button', { name: 'Keep task', exact: true }).click(); await closePanel();
    await page.getByLabel('Status for Retained draft', { exact: true }).selectOption('Done');
    await page.waitForFunction(() => document.querySelector('[aria-label="Status for Retained draft"]').value === 'Todo');
    await page.evaluate(() => { window.blockWrites = false; });
    const saved = await page.evaluate(storageKey => localStorage.getItem(storageKey), key);
    await page.evaluate(storageKey => localStorage.setItem(storageKey, '{broken'), key);
    await page.reload(); await page.locator('#list-error').waitFor({ state: 'visible' });
    assert.match(await page.locator('#list-error-copy').innerText(), /not been overwritten/);
    assert.equal(await page.evaluate(storageKey => localStorage.getItem(storageKey), key), '{broken');
    await page.evaluate(({ storageKey, value }) => localStorage.setItem(storageKey, value), { storageKey: key, value: saved });
    await page.getByRole('button', { name: 'Try again', exact: true }).click(); await loaded(2);
    assert.deepEqual(errors, []);
    console.log('Browser checks passed: CRUD, reload persistence, validation, search/filter/sort, statuses, delete cancellation, empty/error recovery, XSS escaping, and mobile layout.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
